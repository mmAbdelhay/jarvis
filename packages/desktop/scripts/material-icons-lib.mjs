// Builds renderer/vendor/material-icons from an unpacked material-icon-theme
// package (dist/material-icons.json, icons/, LICENSE). The package is data to
// this script: nothing in it is ever imported or run. Every icon it copies is
// checked first, and nothing is written unless all of them pass.
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { join } from "node:path";

const MAX_SVG_BYTES = 64 * 1024;
const ICON_PATH = /^(?:\.\/)?(?:\.\.\/)?icons\/([^/\\]+\.svg)$/;

/** A plain `name.svg`: no path, no dot-file, nothing a file system reads as more. */
export function plainFileName(name) {
  return (
    typeof name === "string" &&
    /^[A-Za-z0-9][A-Za-z0-9._-]*\.svg$/.test(name) &&
    !name.includes("..")
  );
}

/** `{ ok: true }` for a plain drawing; otherwise the first thing that is not one. */
export function checkSvg(text) {
  if (typeof text !== "string") return { ok: false, reason: "not text" };
  if (text.length > MAX_SVG_BYTES) return { ok: false, reason: "too large" };
  if (/<\s*script/i.test(text)) return { ok: false, reason: "script" };
  if (/<\s*(?:foreignObject|iframe|object|embed|link|meta|base)\b/i.test(text)) {
    return { ok: false, reason: "embedded content" };
  }
  if (/<!\s*ENTITY|<!\s*DOCTYPE[^>]*\[/i.test(text)) return { ok: false, reason: "entity" };
  if (/[\s"'/]on[a-z]+\s*=/i.test(text)) return { ok: false, reason: "event handler" };
  if (/javascript\s*:/i.test(text)) return { ok: false, reason: "javascript" };
  if (/@import/i.test(text)) return { ok: false, reason: "import" };
  for (const match of text.matchAll(/(?:xlink:)?href\s*=\s*(["'])(.*?)\1/gi)) {
    if (!(match[2] ?? "").startsWith("#")) return { ok: false, reason: "outside href" };
  }
  for (const match of text.matchAll(/url\(\s*(["']?)([^)"']*)\1\s*\)/gi)) {
    if (!(match[2] ?? "").trim().startsWith("#")) return { ok: false, reason: "outside url" };
  }
  return { ok: true };
}

const MAPS = ["fileNames", "fileExtensions", "folderNames", "folderNamesExpanded", "languageIds"];

/** Reads, checks and writes. Returns what it wrote; throws before writing anything. */
export function vendorIcons({ from, to }) {
  const source = JSON.parse(readFileSync(join(from, "dist", "material-icons.json"), "utf8"));
  const version = JSON.parse(readFileSync(join(from, "package.json"), "utf8")).version;
  const definitions = source.iconDefinitions ?? {};
  const fileOf = new Map();
  const resolve = (id) => {
    if (typeof id !== "string") throw new Error(`icon id is not a string: ${String(id)}`);
    const known = fileOf.get(id);
    if (known !== undefined) return known;
    const definition = Object.hasOwn(definitions, id) ? definitions[id] : undefined;
    const match = ICON_PATH.exec(definition?.iconPath ?? "");
    const name = match?.[1];
    if (name === undefined || !plainFileName(name)) {
      throw new Error(`icon "${id}" does not name a plain svg file`);
    }
    fileOf.set(id, name);
    return name;
  };

  const table = {
    version,
    file: resolve(source.file),
    folder: resolve(source.folder),
    folderExpanded: resolve(source.folderExpanded),
  };
  for (const map of MAPS) {
    const entries = new Map();
    for (const [key, id] of Object.entries(source[map] ?? {})) {
      const lower = key.toLowerCase();
      if (!entries.has(lower)) entries.set(lower, resolve(id));
    }
    table[map] = Object.fromEntries(entries);
  }

  const files = [...new Set(fileOf.values())].sort();
  const texts = new Map();
  for (const name of files) {
    const path = join(from, "icons", name);
    if (!existsSync(path) || !statSync(path).isFile()) throw new Error(`missing icon ${name}`);
    const text = readFileSync(path, "utf8");
    const verdict = checkSvg(text);
    if (!verdict.ok) throw new Error(`${name}: ${verdict.reason}`);
    texts.set(name, text);
  }

  rmSync(join(to, "icons"), { recursive: true, force: true });
  mkdirSync(join(to, "icons"), { recursive: true });
  copyFileSync(join(from, "LICENSE"), join(to, "LICENSE"));
  for (const name of files) copyFileSync(join(from, "icons", name), join(to, "icons", name));
  writeFileSync(
    join(to, "table.mjs"),
    `// Generated by scripts/vendor-material-icons.mjs from material-icon-theme ${version} (MIT). Do not edit.\nexport default ${JSON.stringify(table)};\n`,
  );
  writeFileSync(
    join(to, "table.d.mts"),
    `export type MaterialIconTable = {
  version: string;
  file: string;
  folder: string;
  folderExpanded: string;
  fileNames: Record<string, string>;
  fileExtensions: Record<string, string>;
  folderNames: Record<string, string>;
  folderNamesExpanded: Record<string, string>;
  languageIds: Record<string, string>;
};
declare const table: MaterialIconTable;
export default table;
`,
  );
  return { icons: files.length, version };
}
